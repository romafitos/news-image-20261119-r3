def load_data(here):
    stories = []
    with open(os.path.join(here, "stories.json"), encoding="utf-8") as fh:
        for ln in fh:
            ln = ln.strip()
            if ln:
                stories.append(json.loads(ln))
    rings = []
    cur = []
    with open(os.path.join(here, "land.json"), encoding="utf-8") as fh:
        for ln in fh:
            ln = ln.strip()
            if not ln:
                if cur:
                    rings.append(cur)
                    cur = []
            else:
                cur.append(json.loads(ln))
    if cur:
        rings.append(cur)
    data = {"rings": rings}
    for obj in stories:
        k = obj["k"]
        if k in ("head", "chain", "datecheck"):
            data[k] = obj
        elif k in ("pin", "hero", "mid", "num", "spot"):
            key = "heroes" if k == "hero" else k + "s"
            data.setdefault(key, []).append(obj)
        elif k == "idx":
            data.setdefault("idxs", []).append(obj)
    return data


