# ---- bitmap font scaler and text helpers ----
# A glyph is a 20x20 source grid (pen columns -2..+17, rows 0..19).
# Scaling is area sampling: an output pixel is ink when at least half
# of the source area it covers is ink.
_glyph_cache = {}


def _scaled_runs(font, ch, size):
    key = (font, ch, size)
    got = _glyph_cache.get(key)
    if got is not None:
        return got
    adv, rows_hex = FONTS[font][ch]
    scale = size / 15.0
    cw = max(1, round(20 * scale))
    chh = max(1, round(20 * scale))
    src = []
    for r in range(20):
        val = int(rows_hex[r * 5:(r + 1) * 5], 16)
        src.append([1 if (val >> (19 - c)) & 1 else 0 for c in range(20)])
    runs = []
    for orow in range(chh):
        r0 = orow / scale
        r1 = (orow + 1) / scale
        spans = []
        cur = None
        for ocol in range(cw):
            c0 = ocol / scale
            c1 = (ocol + 1) / scale
            ink_area = 0.0
            tot_area = 0.0
            sr_lo = int(r0)
            if sr_lo < 0:
                sr_lo = 0
            sr_hi = int(r1)
            if sr_hi > 19:
                sr_hi = 19
            sc_lo = int(c0)
            if sc_lo < 0:
                sc_lo = 0
            sc_hi = int(c1)
            if sc_hi > 19:
                sc_hi = 19
            for sr in range(sr_lo, sr_hi + 1):
                ov_r = min(r1, sr + 1) - max(r0, sr)
                if ov_r <= 0:
                    continue
                srow = src[sr]
                for sc in range(sc_lo, sc_hi + 1):
                    ov_c = min(c1, sc + 1) - max(c0, sc)
                    if ov_c <= 0:
                        continue
                    area = ov_r * ov_c
                    tot_area += area
                    if srow[sc]:
                        ink_area += area
            ink = tot_area > 0 and ink_area * 2 >= tot_area
            if ink and cur is None:
                cur = ocol
            elif not ink and cur is not None:
                spans.append((cur, ocol - 1))
                cur = None
        if cur is not None:
            spans.append((cur, cw - 1))
        runs.append(spans)
    _glyph_cache[key] = runs
    return runs


def _adv_at(font, ch, size):
    adv = FONTS[font][ch][0]
    got = round(adv * size / 15.0)
    return got if got > 1 else 1


def text_w(s, font, size):
    total = 0
    for ch in s:
        total += _adv_at(font, ch, size)
    return total


def draw_text(buf, x, y, s, font, size, color, align="left"):
    if align == "center":
        x = x - text_w(s, font, size) // 2
    elif align == "right":
        x = x - text_w(s, font, size)
    scale = size / 15.0
    left = round(2 * scale)
    pen = x
    for ch in s:
        runs = _scaled_runs(font, ch, size)
        ox = pen - left
        for r, spans in enumerate(runs):
            for (a, b) in spans:
                _hspan(buf, ox + a, y + r, b - a + 1, color)
        pen += _adv_at(font, ch, size)
    return pen


def wrap_text(s, font, size, width):
    lines = []
    cur = ""
    for wd in s.split(" "):
        trial = wd if not cur else cur + " " + wd
        if text_w(trial, font, size) <= width or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = wd
    if cur:
        lines.append(cur)
    return lines


def trunc_text(s, font, size, width):
    if text_w(s, font, size) <= width:
        return s
    while s and text_w(s + "…", font, size) > width:
        s = s[:-1]
    return s + "…"


def changes_lines(text, font, size, width, max_lines):
    full = "WHAT CHANGES: " + text
    lines = wrap_text(full, font, size, width)
    if len(lines) > max_lines:
        lines = lines[:max_lines]
        lines[-1] = trunc_text(lines[-1], font, size, width)
    return lines

# ---- pixel buffer and primitives ----
# One flat bytearray, 1024x1024x3, row-major RGB. Every draw clips.


def new_buf():
    buf = bytearray(W * H * 3)
    r, g, b = PAPER
    for i in range(0, len(buf), 3):
        buf[i] = r
        buf[i + 1] = g
        buf[i + 2] = b
    return buf


def _px(buf, x, y, color):
    if 0 <= x < W and 0 <= y < H:
        i = (y * W + x) * 3
        buf[i] = color[0]
        buf[i + 1] = color[1]
        buf[i + 2] = color[2]


def _hspan(buf, x, y, w, color):
    if y < 0 or y >= H or w <= 0:
        return
    if x < 0:
        w += x
        x = 0
    if x + w > W:
        w = W - x
    if w <= 0:
        return
    i = (y * W + x) * 3
    trip = bytes(color)
    buf[i:i + w * 3] = trip * w


def fill_rect(buf, x, y, w, h, color):
    for yy in range(y, y + h):
        _hspan(buf, x, yy, w, color)


def vgrad(buf, x, y, w, h, top, bot):
    for i in range(h):
        f = i / max(1, h - 1)
        c = (round(top[0] + (bot[0] - top[0]) * f),
             round(top[1] + (bot[1] - top[1]) * f),
             round(top[2] + (bot[2] - top[2]) * f))
        _hspan(buf, x, y + i, w, c)


def circle(buf, cx, cy, r, color):
    for y in range(cy - r, cy + r + 1):
        dy = y - cy
        hw = int(math.sqrt(max(0, r * r - dy * dy)))
        _hspan(buf, cx - hw, y, 2 * hw + 1, color)


def ellipse(buf, cx, cy, rx, ry, color):
    for y in range(cy - ry, cy + ry + 1):
        dy = y - cy
        inside = 1.0 - (dy * dy) / float(ry * ry)
        if inside < 0:
            continue
        hw = int(rx * math.sqrt(inside))
        _hspan(buf, cx - hw, y, 2 * hw + 1, color)


def fill_poly(buf, pts, color):
    ys = [p[1] for p in pts]
    y0 = max(0, int(math.ceil(min(ys) - 0.5)))
    y1 = min(H - 1, int(math.floor(max(ys) - 0.5)))
    n = len(pts)
    for y in range(y0, y1 + 1):
        yc = y + 0.5
        xs = []
        for i in range(n):
            x1, y1p = pts[i]
            x2, y2p = pts[(i + 1) % n]
            if (y1p <= yc < y2p) or (y2p <= yc < y1p):
                t = (yc - y1p) / (y2p - y1p)
                xs.append(x1 + t * (x2 - x1))
        xs.sort()
        for i in range(0, len(xs) - 1, 2):
            a = int(math.ceil(xs[i]))
            b = int(math.floor(xs[i + 1]))
            _hspan(buf, a, y, b - a + 1, color)


def line(buf, x0, y0, x1, y1, color):
    dx = abs(x1 - x0)
    dy = -abs(y1 - y0)
    sx = 1 if x0 < x1 else -1
    sy = 1 if y0 < y1 else -1
    err = dx + dy
    while True:
        _px(buf, x0, y0, color)
        if x0 == x1 and y0 == y1:
            break
        e2 = 2 * err
        if e2 >= dy:
            err += dy
            x0 += sx
        if e2 <= dx:
            err += dx
            y0 += sy


def outline_poly(buf, pts, color):
    n = len(pts)
    for i in range(n):
        x1, y1 = pts[i]
        x2, y2 = pts[(i + 1) % n]
        line(buf, x1, y1, x2, y2, color)


def halo_text(buf, x, y, s, font, size, color):
    white = (255, 255, 255)
    draw_text(buf, x - 1, y, s, font, size, white)
    draw_text(buf, x + 1, y, s, font, size, white)
    draw_text(buf, x, y - 1, s, font, size, white)
    draw_text(buf, x, y + 1, s, font, size, white)
    draw_text(buf, x, y, s, font, size, color)

# ---- PNG encoder (hand-written, filter 0, zlib level 9) ----


def _chunk(typ, data):
    return (struct.pack(">I", len(data)) + typ + data +
            struct.pack(">I", binascii.crc32(typ + data) & 0xffffffff))


def png_bytes(buf):
    raw = bytearray()
    for y in range(H):
        raw.append(0)
        raw += buf[y * W * 3:(y + 1) * W * 3]
    comp = zlib.compress(bytes(raw), 9)
    ihdr = struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + _chunk(b"IHDR", ihdr) +
            _chunk(b"IDAT", comp) + _chunk(b"IEND", b""))


# ---- PNG decoder (reads media hero files; any failure falls back) ----


def decode_png(path):
    data = open(path, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("bad signature")
    pos = 8
    ihdr = None
    plte = None
    idat = bytearray()
    while pos < len(data):
        ln = struct.unpack(">I", data[pos:pos + 4])[0]
        typ = data[pos + 4:pos + 8]
        body = data[pos + 8:pos + 8 + ln]
        if typ == b"IHDR":
            w, h, bd, ct, comp, filt, inter = struct.unpack(">IIBBBBB", body)
            ihdr = (w, h, bd, ct, inter)
        elif typ == b"PLTE":
            plte = body
        elif typ == b"IDAT":
            idat += body
        elif typ == b"IEND":
            break
        pos += 12 + ln
    if ihdr is None:
        raise ValueError("no IHDR")
    w, h, bd, ct, inter = ihdr
    if inter != 0:
        raise ValueError("interlaced")
    if bd not in (8, 16):
        raise ValueError("bit depth")
    if ct not in (0, 2, 3, 4, 6):
        raise ValueError("colour type")
    if w * h > 3000000:
        raise ValueError("too big")
    nch = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ct]
    bps = nch * (bd // 8)
    stride = w * bps
    raw = zlib.decompress(bytes(idat))
    if len(raw) != h * (1 + stride):
        raise ValueError("size mismatch")
    rows = []
    prev = bytearray(stride)
    for y in range(h):
        f = raw[y * (1 + stride)]
        cur = raw[y * (1 + stride) + 1:(y + 1) * (1 + stride)]
        out = bytearray(stride)
        if f == 0:
            out[:] = cur
        elif f == 1:
            for i in range(stride):
                left = out[i - bps] if i >= bps else 0
                out[i] = (cur[i] + left) & 0xff
        elif f == 2:
            for i in range(stride):
                out[i] = (cur[i] + prev[i]) & 0xff
        elif f == 3:
            for i in range(stride):
                left = out[i - bps] if i >= bps else 0
                out[i] = (cur[i] + (left + prev[i]) // 2) & 0xff
        elif f == 4:
            for i in range(stride):
                left = out[i - bps] if i >= bps else 0
                up = prev[i]
                ul = prev[i - bps] if i >= bps else 0
                pp = left + up - ul
                pa = abs(pp - left)
                pb = abs(pp - up)
                pc = abs(pp - ul)
                if pa <= pb and pa <= pc:
                    pr = left
                elif pb <= pc:
                    pr = up
                else:
                    pr = ul
                out[i] = (cur[i] + pr) & 0xff
        else:
            raise ValueError("bad filter")
        rows.append(bytes(out))
        prev = out
    return {"w": w, "h": h, "bd": bd, "ct": ct, "plte": plte, "rows": rows}


def _over_white(r, g, b, a):
    if a == 255:
        return (r, g, b)
    return ((r * a + 255 * (255 - a)) // 255,
            (g * a + 255 * (255 - a)) // 255,
            (b * a + 255 * (255 - a)) // 255)


def px_color(img, x, y):
    bd = img["bd"]
    ct = img["ct"]
    row = img["rows"][y]
    if bd == 16:
        if ct == 2:
            off = x * 6
            return (row[off], row[off + 2], row[off + 4])
        if ct == 6:
            off = x * 8
            return _over_white(row[off], row[off + 2], row[off + 4],
                               row[off + 6])
        if ct == 0:
            v = row[x * 2]
            return (v, v, v)
        if ct == 4:
            off = x * 4
            return _over_white(row[off], row[off], row[off], row[off + 2])
        if ct == 3:
            idx = row[x * 2]
            pl = img["plte"]
            return (pl[idx * 3], pl[idx * 3 + 1], pl[idx * 3 + 2])
    else:
        if ct == 2:
            off = x * 3
            return (row[off], row[off + 1], row[off + 2])
        if ct == 6:
            off = x * 4
            return _over_white(row[off], row[off + 1], row[off + 2],
                               row[off + 3])
        if ct == 0:
            v = row[x]
            return (v, v, v)
        if ct == 4:
            off = x * 2
            return _over_white(row[off], row[off], row[off], row[off + 1])
        if ct == 3:
            idx = row[x]
            pl = img["plte"]
            return (pl[idx * 3], pl[idx * 3 + 1], pl[idx * 3 + 2])
    raise ValueError("colour type")


def cover_paste(buf, img, px, py, pw, ph):
    iw, ih = img["w"], img["h"]
    scale = max(pw / iw, ph / ih)
    sw, sh = iw * scale, ih * scale
    ox, oy = (pw - sw) / 2.0, (ph - sh) / 2.0
    for yy in range(ph):
        sy = int((yy - oy) / scale)
        if sy < 0:
            sy = 0
        elif sy >= ih:
            sy = ih - 1
        for xx in range(pw):
            sx = int((xx - ox) / scale)
            if sx < 0:
                sx = 0
            elif sx >= iw:
                sx = iw - 1
            _px(buf, px + xx, py + yy, px_color(img, sx, sy))

