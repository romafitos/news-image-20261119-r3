def _clip_edge(pts, keep, cross):
    if not pts:
        return []
    out = []
    for i in range(len(pts)):
        cur = pts[i]
        prev = pts[i - 1]
        cin = keep(cur)
        pin = keep(prev)
        if cin:
            if not pin:
                out.append(cross(prev, cur))
            out.append(cur)
        elif pin:
            out.append(cross(prev, cur))
    return out


def clip_rect(pts, x0, y0, x1, y1):
    pts = _clip_edge(pts, lambda p: p[0] >= x0,
                     lambda a, b: (x0, a[1] + (b[1] - a[1]) * (x0 - a[0]) / (b[0] - a[0])) if b[0] != a[0] else (x0, a[1]))
    pts = _clip_edge(pts, lambda p: p[0] <= x1,
                     lambda a, b: (x1, a[1] + (b[1] - a[1]) * (x1 - a[0]) / (b[0] - a[0])) if b[0] != a[0] else (x1, a[1]))
    pts = _clip_edge(pts, lambda p: p[1] >= y0,
                     lambda a, b: (a[0] + (b[0] - a[0]) * (y0 - a[1]) / (b[1] - a[1]), y0) if b[1] != a[1] else (a[0], y0))
    pts = _clip_edge(pts, lambda p: p[1] <= y1,
                     lambda a, b: (a[0] + (b[0] - a[0]) * (y1 - a[1]) / (b[1] - a[1]), y1) if b[1] != a[1] else (a[0], y1))
    return pts


